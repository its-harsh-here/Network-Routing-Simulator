// Turns the CSV results into docs/benchmarks.md and the SVG charts. Every result in the report
// is read from the CSV files the benchmarks wrote, and every setting from the code that used it;
// the text around them is fixed or computed.
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { resolveConfig } from '../src/sim/config.ts'
import { PRESET_LINK } from '../src/topology/presets.ts'
import { CONVERGENCE_SETTINGS } from './convergence.ts'
import { AVERAGE_DEGREE } from './dijkstra.ts'
import { COST_RANGE, fromCsv } from './lib.ts'
import { groupedBarPanels, logLogLineChart } from './svg.ts'

type Row = Record<string, string>

/** The engine's defaults, which every benchmark simulation uses unless it says otherwise. */
const ENGINE = resolveConfig()
const LINK = `${PRESET_LINK.bandwidthBps / 1e6} Mbps, ${PRESET_LINK.delayMs} ms`

const SETUP_COLOURS: Record<string, string> = {
  'link-state': '#0284c7',
  'DV + split horizon': '#d97706',
  'DV, no split horizon': '#dc2626',
}

function readRows(dir: string, file: string): Row[] | null {
  const path = join(dir, file)
  return existsSync(path) ? fromCsv(readFileSync(path, 'utf8')) : null
}

const num = (value: string) => Number(value)
const fmt = (value: number, digits = 1) =>
  value.toLocaleString('en', { maximumFractionDigits: digits, minimumFractionDigits: 0 })

/** A markdown table. */
function table(header: string[], rows: string[][], alignRight: boolean[] = []): string {
  const line = (cells: string[]) => `| ${cells.join(' | ')} |`
  const rule = header.map((_, i) => (alignRight[i] ? '---:' : '---'))
  return [line(header), line(rule), ...rows.map(line)].join('\n')
}

/**
 * Writes docs/benchmarks.md, docs/dijkstra.svg and docs/convergence.svg from the CSV files in
 * `resultsDir`. A benchmark that has not been run yet gets a note instead of a section.
 */
export function writeReport(resultsDir: string, docsDir: string, command: string): void {
  const machine = existsSync(join(resultsDir, 'machine.json'))
    ? (JSON.parse(readFileSync(join(resultsDir, 'machine.json'), 'utf8')) as Record<string, string>)
    : null
  const parts: string[] = ['# Benchmarks', '']
  parts.push(
    `Generated by \`${command}\`${machine ? ` on ${machine.date}` : ''}. Every number on this page is read from the CSV files in [bench/results](../bench/results), which the benchmark scripts write; none is typed by hand. Run \`npm run bench\` to measure again on your machine.`,
  )
  if (machine) {
    parts.push(
      '',
      `Machine: ${machine.cpu}, ${machine.cores} logical cores, Node ${machine.node}, ${machine.os}. Everything runs on one thread.`,
    )
  }
  parts.push('', dijkstraSection(resultsDir, docsDir))
  parts.push('', simulatorSection(resultsDir))
  parts.push('', convergenceSection(resultsDir, docsDir))
  writeFileSync(join(docsDir, 'benchmarks.md'), parts.join('\n') + '\n')
}

function dijkstraSection(resultsDir: string, docsDir: string): string {
  const rows = readRows(resultsDir, 'dijkstra.csv')
  const out = ['## 1. Dijkstra: binary heap vs naive O(V²)', '']
  if (rows === null)
    return [...out, '_Not run yet: `npm run bench -- --only=dijkstra`._'].join('\n')
  const runs = rows[0].runs
  out.push(
    `Random connected graphs with average degree ${AVERAGE_DEGREE} (a random spanning tree plus random extra links, so E = ${AVERAGE_DEGREE / 2}V, costs uniform in [${COST_RANGE[0]}, ${COST_RANGE[1]})), one seeded graph per size. Each version computes shortest paths from one router; both are run once untimed first (to let the JIT compile them, and to check they give the same distances), then ${runs} timed runs each, alternating. The table shows the median of the ${runs} runs.`,
    '',
  )
  out.push(
    table(
      ['V', 'links', 'heap (ms)', 'naive (ms)', 'heap is faster by'],
      rows.map((r) => [
        fmt(num(r.nodes), 0),
        fmt(num(r.links), 0),
        fmt(num(r.heap_median_ms), 3),
        fmt(num(r.naive_median_ms), 3),
        `${fmt(num(r.speedup), 1)}×`,
      ]),
      [true, true, true, true, true],
    ),
  )
  writeFileSync(
    join(docsDir, 'dijkstra.svg'),
    logLogLineChart({
      title: 'Dijkstra: median time from one source (log-log)',
      xLabel: `routers V (average degree ${AVERAGE_DEGREE})`,
      yLabel: 'time',
      yUnit: ' ms',
      series: [
        {
          name: 'binary heap',
          colour: '#0284c7',
          points: rows.map((r) => ({ x: num(r.nodes), y: num(r.heap_median_ms) })),
        },
        {
          name: 'naive O(V²)',
          colour: '#dc2626',
          points: rows.map((r) => ({ x: num(r.nodes), y: num(r.naive_median_ms) })),
        },
      ],
    }),
  )
  out.push('', '![Dijkstra time against V, log-log](dijkstra.svg)', '')

  // Observations, computed from the numbers above.
  const first = rows[0]
  const last = rows[rows.length - 1]
  const slopeBetween = (a: Row, b: Row, key: string) =>
    Math.log(num(b[key]) / num(a[key])) / Math.log(num(b.nodes) / num(a.nodes))
  if (rows.length >= 2) {
    const a = rows[rows.length - 2]
    const v1 = num(a.nodes)
    const v2 = num(last.nodes)
    const vLogV = (v: number) => (v + 2 * v) * Math.log2(v) // (V + E) log V with E = 2V
    const predictedHeap = Math.log(vLogV(v2) / vLogV(v1)) / Math.log(v2 / v1)
    out.push(
      `On a log-log chart a running time of c·V^k is a straight line of slope k. Between the two largest sizes (V = ${fmt(v1, 0)} and ${fmt(v2, 0)}) the naive version's slope is ${slopeBetween(a, last, 'naive_median_ms').toFixed(2)} (O(V²) predicts 2) and the heap version's is ${slopeBetween(a, last, 'heap_median_ms').toFixed(2)} (O((V + E) log V) predicts ${predictedHeap.toFixed(2)}). Over the whole range from V = ${fmt(num(first.nodes), 0)} both slopes are lower (${slopeBetween(first, last, 'naive_median_ms').toFixed(2)} and ${slopeBetween(first, last, 'heap_median_ms').toFixed(2)}): on small graphs the fixed costs (allocating arrays and maps, walking the adjacency lists) take most of the time, not the part that grows fastest.`,
    )
    // Time per elementary step: a scanned node for the naive version, one (V + E) log V unit
    // for the heap version. Their ratio is why the heap's lead is far below V / log V.
    const naiveStepNs = (num(last.naive_median_ms) * 1e6) / (v2 * v2)
    const heapStepNs = (num(last.heap_median_ms) * 1e6) / vLogV(v2)
    out.push(
      '',
      `At V = ${fmt(v2, 0)} the heap version is ${fmt(num(last.speedup), 0)}× faster, far less than the V / log V ≈ ${fmt(v2 / Math.log2(v2), 0)}× the step counts alone suggest. The naive inner loop is a tight scan of a plain array, about ${naiveStepNs.toFixed(1)} ns per node; the heap version spends about ${heapStepNs.toFixed(1)} ns per (V + E) log V step on Map lookups, allocating heap entries and pushing up to E of them (lazy deletion), so its constant factor is ${fmt(heapStepNs / naiveStepNs, 0)}× larger.`,
    )
  }
  const naiveWins = rows.filter((r) => num(r.speedup) < 1)
  if (naiveWins.length > 0) {
    out.push(
      '',
      `The naive version is faster at V = ${naiveWins.map((r) => fmt(num(r.nodes), 0)).join(', ')}: on small graphs its plain arrays and simple loop beat the heap's Map lookups and object allocations, before V² catches up with it.`,
    )
  }
  return out.join('\n')
}

function simulatorSection(resultsDir: string): string {
  const rows = readRows(resultsDir, 'simulator.csv')
  const out = ['## 2. Simulator speed', '']
  if (rows === null)
    return [...out, '_Not run yet: `npm run bench -- --only=simulator`._'].join('\n')
  const speeds = rows.map((r) => num(r.events_per_second)).sort((x, y) => x - y)
  const medianSpeed = speeds[Math.floor(speeds.length / 2)]
  const mid = rows.find((r) => num(r.events_per_second) === medianSpeed) as Row
  out.push(
    `A ${Math.round(Math.sqrt(num(mid.routers)))}x${Math.round(Math.sqrt(num(mid.routers)))} grid (preset links: ${LINK}) with ${fmt(num(mid.packets_per_second), 0)} packets per second network-wide, ${ENGINE.routing} routing, queues of ${ENGINE.queueCapacity} packets, stats sampled every ${ENGINE.statsIntervalMs} ms, run for ${mid.sim_seconds} simulated seconds. An event is anything the engine takes off its queue: a packet arriving, a transmission finishing, a new packet from the traffic generator, a stats sample. Each run uses a fresh simulator with the same seed, so all runs do the same work.`,
    '',
  )
  out.push(
    table(
      ['run', 'events', 'wall time (s)', 'events / s', 'sim s per real s', 'packets', 'dropped'],
      rows.map((r) => [
        r.run,
        fmt(num(r.events), 0),
        fmt(num(r.wall_ms) / 1000, 2),
        fmt(num(r.events_per_second), 0),
        `${fmt(num(r.speed_vs_real_time), 2)}×`,
        fmt(num(r.generated), 0),
        `${fmt(num(r.drop_percent), 2)}%`,
      ]),
      [true, true, true, true, true, true, true],
    ),
  )
  out.push(
    '',
    `Median: **${fmt(medianSpeed, 0)} events per second**, ${fmt(num(mid.events) / num(mid.generated), 1)} events per packet. ${fmt(num(mid.drop_percent), 2)}% of the packets were dropped (${fmt(num(mid.dropped_queue_full), 0)} because a queue was full), so the busiest links were saturated: the load is heavy.`,
  )
  return out.join('\n')
}

function convergenceSection(resultsDir: string, docsDir: string): string {
  const rows = readRows(resultsDir, 'convergence.csv')
  const out = ['## 3. Protocol convergence', '']
  if (rows === null)
    return [...out, '_Not run yet: `npm run bench -- --only=convergence`._'].join('\n')
  const failures = rows[0].failures
  out.push(
    `For each network, ${failures} links that are not bridges are chosen at random (fixed seed), so every cut leaves the network connected. Each link is cut once, in a fresh simulation under each routing setup, with the same seed and so the same traffic (${fmt(CONVERGENCE_SETTINGS.packetsPerSecond, 0)} packets per second). Links are preset links (${LINK}; the mesh's delays grow with distance). The network runs ${CONVERGENCE_SETTINGS.warmupMs / 1000} s before the cut and is watched for ${CONVERGENCE_SETTINGS.watchMs / 1000} s after it. Failures are noticed after ${ENGINE.detectionDelayMs} ms; distance-vector advertises every ${ENGINE.dvPeriodMs} ms (and at once when routes change), with infinity at 16 and no poison reverse. Per-failure numbers are in [convergence-failures.csv](../bench/results/convergence-failures.csv).`,
    '',
    '- **Convergence**: from the cut to the last forwarding-table change it caused.',
    '- **Settled**: from the cut until the protocol was quiet: no link-state advertisement in flight, or (distance-vector) one full update period with no change.',
    '- **Packets lost** and **routing messages**: counted from the cut until settled.',
    "- **Missing routes**: router pairs that are still connected at the end but have no route (distance-vector's infinity is 16 hops).",
    '',
  )
  out.push(
    table(
      [
        'network',
        'setup',
        'convergence (ms)',
        'settled (ms)',
        'packets lost',
        'routing messages',
        'missing routes',
      ],
      rows.map((r) => [
        r.topology,
        r.setup,
        fmt(num(r.avg_convergence_ms)),
        r.avg_settled_ms === ''
          ? 'never'
          : fmt(num(r.avg_settled_ms)) +
            (num(r.not_settled) > 0 ? ` (${r.not_settled} never)` : ''),
        fmt(num(r.avg_packets_lost)),
        fmt(num(r.avg_control_messages)),
        fmt(num(r.avg_missing_routes)),
      ]),
      [false, false, true, true, true, true, true],
    ),
  )
  out.push('', `Averages over the ${failures} failures.`)

  const topologies = [...new Set(rows.map((r) => r.topology))]
  const setups = [...new Set(rows.map((r) => r.setup))]
  const value = (topology: string, setup: string, key: string) =>
    num((rows.find((r) => r.topology === topology && r.setup === setup) as Row)[key])
  writeFileSync(
    join(docsDir, 'convergence.svg'),
    groupedBarPanels({
      title: `Link-state vs distance-vector: averages over ${failures} link failures`,
      groups: topologies,
      series: setups.map((name) => ({ name, colour: SETUP_COLOURS[name] ?? '#64748b' })),
      panels: [
        { title: 'Convergence time (ms)', key: 'avg_convergence_ms' },
        { title: 'Packets lost', key: 'avg_packets_lost' },
        { title: 'Routing messages', key: 'avg_control_messages' },
      ].map(({ title, key }) => ({
        title,
        values: topologies.map((t) => setups.map((s) => value(t, s, key))),
      })),
    }),
  )
  out.push('', '![Convergence bars](convergence.svg)', '')

  // Observations, computed from the numbers above.
  for (const topology of topologies) {
    const fastest = setups.reduce((best, s) =>
      value(topology, s, 'avg_convergence_ms') < value(topology, best, 'avg_convergence_ms')
        ? s
        : best,
    )
    const ls = value(topology, 'link-state', 'avg_control_messages')
    const dv = value(topology, 'DV + split horizon', 'avg_control_messages')
    out.push(
      `- **${topology}**: fastest to converge is ${fastest} (${fmt(value(topology, fastest, 'avg_convergence_ms'))} ms). Distance-vector with split horizon sends ${fmt(dv / ls, 1)}× the routing messages of link-state while converging.`,
    )
    for (const setup of setups) {
      const missing = value(topology, setup, 'avg_missing_routes')
      if (missing > 0) {
        out.push(
          `  ${setup} ends with ${fmt(missing)} router pairs on average that are connected but have no route: after the cut some routers are 16 or more hops apart, and distance-vector counts 16 as infinity.`,
        )
      }
    }
  }
  return out.join('\n')
}
